interface GitDiagnostics {
    fun event(event: GitDiagnosticEvent, metadata: Map<String, String> = emptyMap())
}

object NoOpGitDiagnostics : GitDiagnostics {
    override fun event(event: GitDiagnosticEvent, metadata: Map<String, String>) = Unit
}

class DebugGitDiagnostics : GitDiagnostics {
    override fun event(event: GitDiagnosticEvent, metadata: Map<String, String>) {
        val safe = metadata.filterKeys { it in SAFE_KEYS }
        val suffix = safe.entries.joinToString(" ") { "${it.key}=${it.value}" }
        Log.d(TAG, if (suffix.isBlank()) event.name else "${event.name} $suffix")
    }

    private companion object {
        const val TAG = "GitClonePushGit"
        val SAFE_KEYS = setOf("repositoryId", "phase", "percent", "tokenPresent", "category", "changedCount", "branchPresent", "upstreamPresent", "ahead", "behind", "freshness", "state", "conflictCount", "versionPresent", "resolvedCount", "count", "filesChanged", "binary", "truncated", "scope", "currentBranchPresent", "ontoBranchPresent", "published", "planCount")
    }
}
